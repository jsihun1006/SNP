const {chromium}=require('C:/Users/Administrator/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('node:fs');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const page=await browser.newPage({viewport:{width:800,height:900}});
  const errors=[];
  page.on('pageerror',e=>errors.push(String(e)));
  await page.goto('file:///C:/Users/Administrator/Documents/Codex/2026-11-15/git-x20/work/pitch-preview.html',{waitUntil:'domcontentloaded'});
  const frame=page.frameLocator('iframe');
  await frame.locator('#ball-pitch-view .pitch-dot').first().waitFor({timeout:15000});
  const initial=await frame.locator('[data-position]').innerText();
  const initialDots=await frame.locator('.pitch-dot').count();
  await frame.locator('[data-time]').evaluate(e=>{e.value='1';e.dispatchEvent(new Event('input',{bubbles:true}));});
  const changed=await frame.locator('[data-position]').innerText();
  if(initial===changed)throw Error('Time interaction failed');
  await frame.locator('[data-mode="density"]').click();
  const densityCount=await frame.locator('[data-count]').innerText();
  const cells=await frame.locator('.pitch-grid').count();
  if(!cells)throw Error('Density view did not render');
  if(await frame.locator('[data-time-control]').isVisible())throw Error('Time control should hide in density mode');
  await frame.locator('[data-confidence]').evaluate(e=>{e.value='8';e.dispatchEvent(new Event('input',{bubbles:true}));});
  const filtered=await frame.locator('[data-count]').innerText();
  if(filtered===densityCount)throw Error('Confidence filter did not change density');
  await frame.locator('[data-mode="frame"]').click();
  await frame.locator('[data-confidence]').evaluate(e=>{e.value='1';e.dispatchEvent(new Event('input',{bubbles:true}));});
  await frame.locator('[data-time]').evaluate(e=>{e.value='114';e.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.screenshot({path:'work/pitch-preview-wide.png',fullPage:true});
  await page.setViewportSize({width:340,height:900});
  await page.screenshot({path:'work/pitch-preview-narrow.png',fullPage:true});
  const geometry=await frame.locator('#ball-pitch-view').evaluate(e=>({width:e.clientWidth,scrollWidth:e.scrollWidth,svgWidth:e.querySelector('svg').getBoundingClientRect().width}));
  if(geometry.scrollWidth>geometry.width+1)throw Error('Narrow layout overflow');
  if(errors.length)throw Error(errors.join('\n'));
  const result={passed:true,initial,initialDots,timeChangedTo:changed,densityCount,cells,filtered,geometry,browserErrors:errors};
  fs.writeFileSync('outputs/pitch-visualization-check.json',JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
  await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
